// Variables y tipos de datos:
// Tenemos dos formas de declarar una variable (hay una tercera, en desuso)
let nombre;
nombre = "Martin";

console.log(nombre);

// tambien podemos realizar ambas operaciones en una linea, la declaracion y asignacion

let nombre2 = "Martin";

console.log(nombre2);

// A esto lo llamamos inicializar una variable

// Ademas de let, que puede ser reasignado, tenemos const, que es una constante, y no puede
// ser reasignado

const apellido = "Ramirez";

// La constante debe ser declarada y asignada en la misma linea.

// REGLAS PARA NOMBRAR VARIABLES:
// los nombres deben ser descriptivos y repsetar ciertas reglas

